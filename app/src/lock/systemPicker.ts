/**
 * Пометка «сейчас открыто системное окно, а не другое приложение».
 *
 * Выбор фото, выбор файла, диалог разрешений и «поделиться» уводят приложение в
 * фон: с точки зрения AppState это ровно то же, что уход человека из Cry. Без
 * этой пометки блокировка «спрашивать сразу» требовала бы код после каждой
 * отправки фотографии — то есть была бы бесполезной настройкой.
 *
 * Счётчик, а не флаг: окна могут накладываться (запрос разрешения перед самим
 * выбором файла), и вложенное закрытие не должно снимать пометку раньше времени.
 * Модуль без React намеренно: значение читается из обработчика AppState, куда
 * состояние компонента не дотянуть.
 */
let openCount = 0;

export function isSystemPickerOpen(): boolean {
  return openCount > 0;
}

/** Оборачивает любое действие, открывающее системное окно. */
export async function withSystemPicker<T>(action: () => Promise<T>): Promise<T> {
  openCount += 1;
  try {
    return await action();
  } finally {
    // Небольшая задержка: AppState → "active" приходит после закрытия окна, и
    // без неё пометка успела бы снятьcя до того, как её прочитают.
    setTimeout(() => {
      openCount = Math.max(0, openCount - 1);
    }, 1500);
  }
}
