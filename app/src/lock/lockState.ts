/**
 * Заперто ли приложение прямо сейчас.
 *
 * Флаг вне React намеренно: его читает AppContext в местах, куда состояние
 * компонента не дотянуть (обработчики WS-пакетов, замыкания в интервалах), а
 * владеет им App через useAppLock — то есть уровнем выше.
 *
 * Зачем вообще: экран блокировки перекрывает открытый чат, но приложение при
 * этом «активно» и экран телефона включён. Без этого флага каждое пришедшее
 * сообщение помечалось бы прочитанным, пока телефон лежит запертым, — и у
 * собеседника появлялись бы две галочки под сообщением, которое никто не видел.
 */
let locked = false;

export function setAppLocked(value: boolean): void {
  locked = value;
}

export function isAppLocked(): boolean {
  return locked;
}
