import { Platform, Vibration } from "react-native";

/**
 * Короткий тактильный отклик.
 *
 * Взято из React Native, а не из expo-haptics: expo-haptics — нативный модуль,
 * то есть ещё одна вещь, которой может не оказаться в установленной у людей
 * сборке (см. app/AGENTS.md). `Vibration` живёт в самом React Native, разрешение
 * VIBRATE уже объявлено в app.json, и работает это без новых зависимостей.
 *
 * Чем это хуже expo-haptics: там отклики разной «текстуры» (light/medium/heavy,
 * selection), а здесь только длительность вибромотора. Для отправки сообщения и
 * начала записи разницы на слух нет, а цена — ноль.
 *
 * Длительности намеренно на грани заметности. Отклик должен подтверждать
 * действие, а не сообщать о нём на весь стол: мессенджером пользуются в тишине.
 */
const PATTERNS = {
  /** Отправка сообщения, снятие статуса — самое частое. */
  tap: 8,
  /** Долгое нажатие: жест поймали. */
  press: 14,
  /** Начало записи голосового — здесь отклик важнее всего: экран не смотрят. */
  start: 22,
} as const;

export type HapticKind = keyof typeof PATTERNS;

export function haptic(kind: HapticKind = "tap"): void {
  // На iOS Vibration.vibrate игнорирует длительность и всегда даёт один и тот же
  // отклик длиной ~400 мс — это слишком грубо, поэтому там молчим. Приложение
  // собирается под Android, так что практической потери нет.
  if (Platform.OS !== "android") return;
  try {
    Vibration.vibrate(PATTERNS[kind]);
  } catch {
    // Вибромотора может не быть, а разрешение — быть отозванным. Отклик
    // необязателен: молча продолжаем, ронять из-за него отправку нельзя.
  }
}
