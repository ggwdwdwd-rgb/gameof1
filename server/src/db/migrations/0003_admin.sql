-- Явный признак «распоряжается составом».
--
-- Раньше правило было неявным: админом считался первый зарегистрированный
-- участник. Это ломается на самой частой операции — удалении своего же старого
-- аккаунта после переустановки приложения: права молча переходили к следующему
-- по времени, то есть к другому человеку, и вернуть их было нечем.
ALTER TABLE users ADD COLUMN is_admin INTEGER NOT NULL DEFAULT 0;

-- Сохраняем ровно то состояние, которое было до миграции: главным остаётся
-- первый зарегистрированный. Обновление сервера ничего не меняет само по себе.
UPDATE users SET is_admin = 1
WHERE id = (SELECT id FROM users ORDER BY created_at ASC LIMIT 1);
