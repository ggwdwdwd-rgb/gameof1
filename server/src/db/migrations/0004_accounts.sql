-- Аккаунты вместо «кто получил инвайт — тот и участник».
--
-- Было: участник = устройство, вошедшее по одноразовому коду. Ключи устройства
-- и есть личность, восстановить её нечем, а сервер рассылал ВСЕМ полный список
-- всех участников (roster) — то есть каждый зарегистрированный видел каждого.
--
-- Стало: у человека есть аккаунт (почта + пароль + @тег), к которому
-- привязываются устройства. Регистрация никого никому не показывает: список
-- контактов у каждого свой, и человек попадает в него только если его нашли по
-- тегу или он написал первым.
--
-- Сквозное шифрование не меняется: приватные ключи остаются на устройствах,
-- сервер по-прежнему хранит только публичные и не может прочитать сообщения.
-- Пароль ему нужен исключительно чтобы привязать новое устройство к аккаунту.

-- NULL, а не NOT NULL: у участников, зарегистрированных до этой миграции,
-- аккаунта нет. Они продолжают входить подписью устройства и могут завести
-- почту позже — принудительный сброс отобрал бы у них доступ.
ALTER TABLE users ADD COLUMN email TEXT;
-- Argon2id, тот же примитив, что у PIN-кода блокировки на устройстве.
ALTER TABLE users ADD COLUMN password_hash TEXT;
-- @тег: по нему человека находят. Уникален без учёта регистра — см. индекс ниже.
ALTER TABLE users ADD COLUMN username TEXT;
-- Телефон НЕ подтверждается: SMS-шлюз в РФ подключается только на юрлицо.
-- Это просто ещё один тег, который человек ввёл сам, — и в интерфейсе он так и
-- подписан.
ALTER TABLE users ADD COLUMN phone TEXT;
-- Подтверждена ли почта письмом. Без настроенного SMTP остаётся 0, и почта
-- работает просто как логин.
ALTER TABLE users ADD COLUMN email_verified INTEGER NOT NULL DEFAULT 0;

-- Уникальность без учёта регистра и лишних пробелов: «Anna@mail.ru» и
-- «anna@mail.ru» — один и тот же ящик, а два аккаунта на нём означали бы, что
-- вход по почте неоднозначен.
CREATE UNIQUE INDEX idx_users_email ON users(lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX idx_users_username ON users(lower(username)) WHERE username IS NOT NULL;

-- Личный список контактов.
--
-- Заменяет roster: раньше «участники» были одним общим множеством, теперь у
-- каждого свой список. Связь делается взаимной сразу: чтобы переписка
-- шифровалась, обеим сторонам нужны публичные ключи друг друга, а человек,
-- которому написали первым, должен увидеть чат — как в любом мессенджере.
CREATE TABLE contacts (
  owner_id    TEXT NOT NULL REFERENCES users(id),
  contact_id  TEXT NOT NULL REFERENCES users(id),
  created_at  INTEGER NOT NULL,
  PRIMARY KEY (owner_id, contact_id)
);

CREATE INDEX idx_contacts_owner ON contacts(owner_id);

-- Существующие участники видели друг друга через общий roster. Чтобы обновление
-- сервера не «потеряло» им переписку, разворачиваем прежнее состояние в явные
-- контакты: все со всеми, кроме самих себя. Дальше список растёт только через
-- поиск и первые сообщения.
INSERT INTO contacts (owner_id, contact_id, created_at)
SELECT a.id, b.id, strftime('%s', 'now') * 1000
FROM users a JOIN users b ON a.id != b.id;
