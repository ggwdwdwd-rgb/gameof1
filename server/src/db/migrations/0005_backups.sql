-- Резервная копия переписки, зашифрованная кодовой фразой на устройстве.
--
-- Зачем на сервере: человек ожидает, что после входа с нового телефона чаты
-- будут на месте. Но переписка расшифровывается ключами устройства, а они
-- остаются на прежнем телефоне — сервер хранит только шифротекст и помочь не
-- может. Значит копию делает сам клиент, а сервер её просто держит.
--
-- Сервер НЕ может её прочитать: ключ выводится из кодовой фразы, которая
-- никуда не отправляется. Для сервера это непрозрачный блоб, и это тот же
-- принцип, что с сообщениями.
--
-- Одна копия на участника: история версий здесь не нужна, а место на VPS
-- конечно. Новая копия просто заменяет прежнюю.
CREATE TABLE backups (
  user_id     TEXT PRIMARY KEY REFERENCES users(id),
  -- JSON вида {"v":1,"salt":...,"nonce":...,"ciphertext":...} — см.
  -- packages/crypto/src/backup.ts. Разбирать его серверу нечем и незачем.
  blob        TEXT NOT NULL,
  size_bytes  INTEGER NOT NULL,
  updated_at  INTEGER NOT NULL
);
